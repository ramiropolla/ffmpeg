#ifndef SWSCALE_UOPS_ENTRIES_H
#define SWSCALE_UOPS_ENTRIES_H

/**
 * Lists of kernels, generated by uops_entries_gen for each backend. Every
 * list contains exactly the kernels the backend needs, with the backend's
 * translation policy applied. A list is a macro:
 *
 *   #define SWS_ENTRIES_<LIST>(MACRO, ...)
 *
 * which instantiates, for every kernel:
 *
 *   MACRO(__VA_ARGS__, NAME, TYPE, UOP, BLOCK_SIZE, (ARGS), (INIT))
 *
 * - NAME is a unique identifier of the kernel within its list.
 * - TYPE and UOP are the SwsPixelType and SwsUOpType names without their
 *   SWS_PIXEL_ and SWS_UOP_ prefixes (e.g. U8 and READ_PLANAR), so that
 *   consumers can map them to implementations by token pasting.
 * - ARGS is the mask, followed by the uop parameters as plain values.
 * - INIT is a designated initializer for the SwsUOp fields that identify
 *   the kernel, also valid for SwsUOpEntry.
 *
 * Use SWS_UNPAREN to remove the parentheses around ARGS and INIT.
 */

#define SWS_UNPAREN(...) __VA_ARGS__

#endif /* SWSCALE_UOPS_ENTRIES_H */
